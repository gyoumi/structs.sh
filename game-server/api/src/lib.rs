//! HTTP API types for the structs.sh daily game.
//!
//! The server sends these as JSON, and [`render_ts_bindings`] turns them
//! into the TypeScript types the client reads from `client/src/daily/api.ts`.

mod format;

use std::path::Path;

use chrono::NaiveDate;
use serde::{Deserialize, Serialize};
use ts_rs::TS;

/// The JSDoc banner at the top of the generated TypeScript file.
const BANNER: &str = "/** Generated by ts-rs from game-server/api. Do not edit by hand. */";

/// Today's puzzle as `GET /api/daily` returns it, tagged with its template id.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "template")]
pub enum DailyChallenge {
    /// A `quicksort-most-comparisons` puzzle.
    #[serde(rename = "quicksort-most-comparisons")]
    Quicksort {
        number: u32,
        values: Vec<i32>,
        fixed: Vec<usize>,
        goal: u32,
        #[ts(type = "string")]
        date: NaiveDate,
    },
    /// A `bubble-exact-passes` puzzle.
    #[serde(rename = "bubble-exact-passes", rename_all = "camelCase")]
    Bubble {
        number: u32,
        values: Vec<i32>,
        fixed: Vec<usize>,
        target_passes: u32,
        goal: u32,
        #[ts(type = "string")]
        date: NaiveDate,
    },
    /// An `insertion-beats-merge` puzzle.
    #[serde(rename = "insertion-beats-merge")]
    InsertionBeatsMerge {
        number: u32,
        values: Vec<i32>,
        fixed: Vec<usize>,
        goal: u32,
        #[ts(type = "string")]
        date: NaiveDate,
    },
    /// An `avl-most-rotations` puzzle.
    #[serde(rename = "avl-most-rotations")]
    AvlRotations {
        number: u32,
        values: Vec<i32>,
        fixed: Vec<usize>,
        goal: u32,
        #[ts(type = "string")]
        date: NaiveDate,
    },
    /// A `bst-forced-order` puzzle; it has no fixed slots.
    #[serde(rename = "bst-forced-order", rename_all = "camelCase")]
    BstForcedOrder {
        number: u32,
        values: Vec<i32>,
        target_tree: Vec<i32>,
        goal: u32,
        #[ts(type = "string")]
        date: NaiveDate,
    },
    /// An `upset-bst-beats-avl` puzzle.
    #[serde(rename = "upset-bst-beats-avl")]
    UpsetBstBeatsAvl {
        number: u32,
        values: Vec<i32>,
        fixed: Vec<usize>,
        goal: u32,
        #[ts(type = "string")]
        date: NaiveDate,
    },
    /// A `linked-list-index-drift` puzzle; it has no values to arrange.
    #[serde(rename = "linked-list-index-drift")]
    LinkedListIndexDrift {
        number: u32,
        start: Vec<i32>,
        target: Vec<i32>,
        goal: u32,
        #[ts(type = "string")]
        date: NaiveDate,
    },
}

/// The body of an error response.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
pub struct ApiError {
    /// What went wrong, in words a player can read.
    pub error: String,
}

/// The TypeScript declarations for every API type, as one file.
pub fn render_ts_bindings() -> String {
    format!(
        "{BANNER}\n\n{}\n\n{}\n",
        format::format_decl(&DailyChallenge::decl()),
        format::format_decl(&ApiError::decl())
    )
}

/// Writes [`render_ts_bindings`] to `path`, creating its folder if needed.
pub fn write_ts_bindings(path: &Path) -> std::io::Result<()> {
    if let Some(parent) = path.parent().filter(|p| !p.as_os_str().is_empty()) {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, render_ts_bindings())
}
